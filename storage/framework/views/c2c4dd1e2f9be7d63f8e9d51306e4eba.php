#[Layout('superadmin.layouts.app')]
#[Title('Edit Tenant Type')]
class extends Component {

    public TypeOfTenant $type;

    public string $typeName    = '';
    public string $description = '';

    public function mount(TypeOfTenant $type): void
    {
        abort_unless(Auth::user()?->hasRole('super-admin'), 403, 'Super-admin access only.');

        $this->type        = $type;
        $this->typeName    = $type->type;
        $this->description = $type->description ?? '';
    }

    public function updated(string $property): void
    {
        if (in_array($property, ['typeName', 'description'], true)) {
            $this->$property = trim((string) $this->$property);
        }
    }

    protected function rules(): array
    {
        return [
            'typeName' => [
                'required',
                'string',
                'min:2',
                'max:255',
                Rule::unique('type_of_tenants', 'type')->ignore($this->type->id),
            ],
            'description' => ['nullable', 'string', 'max:1000'],
        ];
    }

    protected function messages(): array
    {
        return [
            'typeName.required' => 'Please enter a name for the business type.',
            'typeName.unique'   => 'A business type with this name already exists.',
            'typeName.min'      => 'The name must be at least 2 characters.',
        ];
    }

    public function update()
    {
        abort_unless(Auth::user()?->hasRole('super-admin'), 403, 'Super-admin access only.');

        $this->typeName    = trim($this->typeName);
        $this->description = trim($this->description);

        $this->validate();

        try {
            DB::transaction(function (): void {
                // Lock the row so two concurrent edits can't clobber
                // each other's changes.
                $locked = TypeOfTenant::query()
                    ->whereKey($this->type->id)
                    ->lockForUpdate()
                    ->firstOrFail();

                $locked->update([
                    'type'        => $this->typeName,
                    'description' => $this->description !== '' ? $this->description : null,
                ]);
            });
        } catch (\Throwable $e) {
            Log::error('Tenant type update failed', [
                'type_id'  => $this->type->id,
                'actor_id' => Auth::id(),
                'error'    => $e->getMessage(),
            ]);
            session()->flash('error', 'Failed to update the tenant type. Please try again.');
            return null;
        }

        session()->flash('message', 'Tenant type updated successfully.');
        return $this->redirectRoute('superadmin.tenant-types.index', navigate: true);
    }
};
